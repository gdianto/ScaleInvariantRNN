# Robustness of the autonomous network regime to recurrent gain and self-coupling perturbations.
#
# The two sweeps are independent:
#   1. vary g while keeping the published self-couplings fixed;
#   2. vary the standard deviation of quenched Gaussian perturbations to the
#      self-couplings while keeping g = 0.4.
#
# Usage:
#   julia scripts/analyze_network_robustness.jl
#   julia scripts/analyze_network_robustness.jl --sweep=g --nets=5 --max-duration=1000 --tag=pilot
#   julia scripts/analyze_network_robustness.jl --sweep=sigma --sigma-values=0,0.05,0.1,0.2
# Other options: --g-values, --alignment, --measurement, --seed,
#                --perturbation-seed, --s, --tag, --force.
